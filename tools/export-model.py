#!/usr/bin/env python3
"""Quantize AuroraTTS-100K into the fixed-point image the DSP and its host
reference share.

Output:
  AURORA.BIN        big-endian 32-bit words, each holding a sign-extended 24-bit
                    DSP word; loaded unchanged by the 68030 and the host tools
  aurora-layout.h   word offset, count and scale of every block in that file

Number formats (see docs/fixed-point.md):
  activation   Q7.16: value = word / 2^16, range +-128
  matrix       per block shift s: value = word / 2^(23-s); a row is
               [bias, w0 .. w(n-1)] and the bias multiplies the constant 1.0
  table        (value, slope) pairs in Q7.16, linear interpolation
"""
import argparse
import json
import math
from pathlib import Path

import numpy as np
from safetensors.numpy import load_file

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "third_party" / "auroratts"

ONE = 1 << 16                 # 1.0 in Q7.16


class Image:
    def __init__(self):
        self.words = []
        self.blocks = []      # (name, offset, count, shift, comment)

    def add(self, name, values, shift=None, comment=""):
        values = [int(v) for v in np.asarray(values).ravel()]
        for v in values:
            assert -(1 << 23) <= v < (1 << 23), (name, v)
        self.blocks.append((name, len(self.words), len(values), shift, comment))
        self.words.extend(values)

    def write(self, binary, header):
        data = b"".join((v & 0xffffffff if v >= 0 else (v + (1 << 32))).to_bytes(4, "big") for v in self.words)
        Path(binary).write_bytes(data)
        lines = ["// Generated by tools/export-model.py; do not edit.",
                 "#pragma once", "",
                 f"#define AURORA_IMAGE_WORDS {len(self.words)}", ""]
        for name, off, cnt, shift, comment in self.blocks:
            ident = name.upper().replace(".", "_")
            if comment:
                lines.append(f"// {comment}")
            lines.append(f"#define AU_{ident}_OFF {off}")
            lines.append(f"#define AU_{ident}_LEN {cnt}")
            if shift is not None:
                lines.append(f"#define AU_{ident}_SHIFT {shift}")
        Path(header).write_text("\n".join(lines) + "\n")


def shift_for(a):
    m = float(np.abs(a).max())
    s = 0
    while m >= (1 << s) * (1 - 2.0 ** -22):
        s += 1
    return s


def q(a, frac_bits):
    return np.round(np.asarray(a, dtype=np.float64) * (1 << frac_bits)).astype(np.int64)


def matrix(img, name, w, b, comment=""):
    """y = W x + b with W (out, in): rows [b, w...] at one shift."""
    w = np.asarray(w, dtype=np.float64).reshape(w.shape[0], -1)
    b = np.zeros(w.shape[0]) if b is None else np.asarray(b, dtype=np.float64)
    rows = np.concatenate([b[:, None], w], 1)
    s = shift_for(rows)
    img.add(name, q(rows, 23 - s), s, comment or f"{w.shape[0]} rows of [bias, {w.shape[1]} weights]")


def norm(img, name, w, b):
    """Layer norm rows [beta, gamma * sqrt(n)]: see fixed.h's layernorm."""
    matrix(img, name, (np.asarray(w) * math.sqrt(len(w)))[:, None], b, "layer norm: [beta, gamma * sqrt(n)]")


def table(img, name, fn, lo, hi, n, comment):
    """n intervals over [lo, hi): (value, slope) pairs, Q7.16."""
    xs = lo + (hi - lo) * np.arange(n + 1) / n
    img.add(name, pairs(q(fn(xs), 16)), None, comment)


def gelu(x):
    from math import erf
    return np.array([0.5 * t * (1 + erf(t / math.sqrt(2))) for t in x])


def mel(f):
    return 2595.0 * np.log10(1.0 + np.asarray(f, dtype=np.float64) / 700.0)


def pairs(v):
    """An interpolation table: the n interval start values, then their n slopes."""
    v = np.asarray(v, dtype=np.int64)
    return np.concatenate([v[:-1], v[1:] - v[:-1]])


def signed24(v):
    v = int(v) & 0xffffff
    return v - (1 << 24) if v >= (1 << 23) else v


# Falcon codec: 25.175 MHz / 1024
FALCON_RATE = 25175000 / 1024


def synth_tables(img, W, cfg):
    """Tables and constants of the harmonic + noise synthesizer (synth.h)."""
    sr, nyq = cfg["sr"], cfg["sr"] / 2
    nyq_mel = float(mel(nyq))
    img.add("tab.sin", np.minimum(np.round(np.sin(2 * np.pi * np.arange(1024) / 1024) * (1 << 23)), (1 << 23) - 1),
            None, "sin(2 pi i / 1024), Q0.23")
    # exp over [-16, 2.03) in steps of 1/32, Q3.20
    xs = -16 + np.arange(578) / 32
    img.add("tab.exp", pairs(np.round(np.exp(xs) * (1 << 20))), None, "exp(x) Q3.20, x = -16 + i/32 (value, slope)")
    # harmonic band position over normalized frequency [0, 1/2) in steps of 1/1024
    nu = np.arange(513) / 1024
    pos = np.clip(mel(nu * sr) / nyq_mel, 0, 1) * (cfg["kh"] - 1)
    img.add("tab.melh", pairs(np.round(pos * ONE)), None, "harmonic band position Q7.16 by normalized frequency")
    # phase increment exp(x) cycles per sample * 2^28 for x = ln(f0 / sr) in [-6, -3.5), Q3.20 input
    xs = -6 + np.arange(641) / 256
    # nodes lowered by h^2/12 so that linear interpolation errs by zero on average:
    # a bias would accumulate in the phase over an utterance
    img.add("tab.inc", pairs(np.round(np.exp(xs) * (1 - 1 / (12 * 256 * 256)) * (1 << 28))), None,
            "f0 / sr * 2^28 by ln(f0 / sr), from -6 in 1/256")
    # noise bins: upstream's linear interpolation matrix, (band, fraction Q.16) per bin
    freqs = np.linspace(0, nyq, 513)
    p = np.clip(mel(freqs) / nyq_mel, 0, 1) * (cfg["kn"] - 1)
    i0 = np.minimum(np.floor(p), cfg["kn"] - 2)
    img.add("tab.nmap", np.stack([i0, np.round((p - i0) * ONE)], 1), None, "noise bin: band, fraction Q.16")
    w = 0.5 - 0.5 * np.cos(2 * np.pi * np.arange(1024) / 1024)
    img.add("tab.win", np.minimum(np.round(w * (1 << 23)), (1 << 23) - 1), None, "periodic Hann, Q0.23")
    img.add("tab.wola", np.round(w * (2 / 3) * (1 << 23)), None, "Hann / 1.5 (overlap-add normalization), Q0.23")
    # phase offsets in whole steps of the 1,024-entry sine table (the table's
    # own resolution): the DSP then adds them to the table address
    th = np.round(np.mod(W["dsp.theta"] / (2 * np.pi), 1.0) * 1024).astype(np.int64) % 1024
    img.add("syn.theta", th, None, "harmonic phase offsets, sine-table steps (0..1023)")
    img.add("syn.fir", q(W["dsp.fir"], 23), None, "output FIR, 65 taps, Q0.23")
    matrix(img, "syn.f0row", np.array([[cfg["f0_std"]]]), np.array([cfg["f0_mean"] - math.log(sr)]),
           "ln(f0 / sr) = f0n * std + mean - ln(sr)")
    # resampler 22,050 -> 24,585 Hz: 32 taps by 256 phases, Kaiser-windowed sinc
    taps, phases, fc = 32, 256, 10800.0
    d = np.arange(taps)[None, :] - (taps // 2 - 1) - np.arange(phases)[:, None] / phases
    h = (2 * fc / sr) * np.sinc(2 * fc / sr * d) * np.kaiser(1001, 7.0)[
        np.clip(np.round((d / (taps / 2 + 0.5) + 1) * 500).astype(int), 0, 1000)]
    h /= h.sum(1, keepdims=True)
    img.add("tab.res", np.round(h * (1 << 23)), None, "resampler: 256 phases of 32 taps, Q0.23")
    ratio = sr / FALCON_RATE
    img.add("syn.const", [
        math.ceil(math.log(60 / sr) * (1 << 20)),    # 0 lowest ln(f0 / sr), Q3.20
        math.floor(math.log(600 / sr) * (1 << 20)),  # 1 highest
        math.ceil(0.475 * (1 << 24)),                # 2 alive: (h inc28) >> 4 below this
        round(ratio * (1 << 24)) - (1 << 24),        # 3 resampler step - 1.0, input samples * 2^24
        0x123456,                                    # 4 noise seed
        signed24(0xFD43FD),                          # 5 LCG multiplier
        signed24(0xC39EC3),                          # 6 LCG increment
        # 7 noise spectrum scale: Re and Im uniform in +-a, a^2 / 3 = 1.5 / 1024,
        #   so that the inverse FFT has variance 1.5 and the overlap-add (Hann / 1.5
        #   at a quarter-frame hop, sum of squares 1.5) unit variance; Q3.20
        round(math.sqrt(3 * 1.5 / 1024) * (1 << 20)),
    ], None, "synthesizer constants")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=ROOT / "build")
    ap.add_argument("--header", type=Path, default=ROOT / "src" / "aurora" / "aurora-layout.h")
    args = ap.parse_args()
    W = {k[len("net."):]: v.astype(np.float64) for k, v in load_file(str(MODEL / "model.safetensors")).items()}
    cfg = json.loads((MODEL / "config.json").read_text())
    img = Image()

    img.add("emb", q(W["emb.weight"], 16), None, "79 x 56 embedding, Q7.16")
    # encoder: one shared block, per-loop norms
    matrix(img, "enc.dw", W["enc.dw.weight"][:, 0, :], W["enc.dw.bias"], "56 channels of [bias, 5 taps]")
    matrix(img, "enc.glu", W["enc.glu.weight"][:, :, 0], W["enc.glu.bias"])
    matrix(img, "enc.ffa", W["enc.ffn.a.weight"][:, :, 0], W["enc.ffn.a.bias"])
    matrix(img, "enc.ffb", W["enc.ffn.b.weight"][:, :, 0], W["enc.ffn.b.bias"])
    for i in range(4):
        for n in ("n1", "n2"):
            norm(img, f"enc.{n}.{i}", W[f"enc.{n}.{i}.w"], W[f"enc.{n}.{i}.b"])
    norm(img, "ctx.norm", W["ctx.norm.w"], W["ctx.norm.b"])
    for d, sfx in (("f", ""), ("b", "_reverse")):
        matrix(img, f"gru.{d}.ih", W["ctx.gru.weight_ih_l0" + sfx], W["ctx.gru.bias_ih_l0" + sfx], "GRU input: r, z, n rows")
        matrix(img, f"gru.{d}.hh", W["ctx.gru.weight_hh_l0" + sfx], W["ctx.gru.bias_hh_l0" + sfx], "GRU hidden: r, z, n rows")
    for p in ("dur", "pit"):
        norm(img, f"{p}.n", W[f"{p}_pred.n.w"], W[f"{p}_pred.n.b"])
        matrix(img, f"{p}.dw", W[f"{p}_pred.dw.weight"][:, 0, :], W[f"{p}_pred.dw.bias"])
        matrix(img, f"{p}.p1", W[f"{p}_pred.p1.weight"][:, :, 0], W[f"{p}_pred.p1.bias"])
        matrix(img, f"{p}.p2", W[f"{p}_pred.p2.weight"][:, :, 0], W[f"{p}_pred.p2.bias"])
        matrix(img, f"{p}.o", W[f"{p}_pred.o.weight"][:, :, 0], W[f"{p}_pred.o.bias"])
    matrix(img, "pit_emb", np.concatenate([W["pit_emb.weight"][:, :, 0], np.zeros((56, 1))], 1), W["pit_emb.bias"],
           "56 rows of [bias, w, 0]: two inputs, the second zero (matrix rows need two)")
    matrix(img, "dec.inp", W["dec.inp.weight"][:, :, 0], W["dec.inp.bias"])
    for i in range(9):
        matrix(img, f"dec.dw.{i}", W[f"dec.dw.{i}.weight"][:, 0, :], W[f"dec.dw.{i}.bias"])
        norm(img, f"dec.ln.{i}", W[f"dec.ln.{i}.w"], W[f"dec.ln.{i}.b"])
    for g in range(3):
        matrix(img, f"dec.ffa.{g}", W[f"dec.ffn.{g}.a.weight"][:, :, 0], W[f"dec.ffn.{g}.a.bias"])
        matrix(img, f"dec.ffb.{g}", W[f"dec.ffn.{g}.b.weight"][:, :, 0], W[f"dec.ffn.{g}.b.bias"])
    norm(img, "dec.out_ln", W["dec.out_ln.w"], W["dec.out_ln.b"])
    matrix(img, "head", W["head.weight"][:, :, 0], W["head.bias"])

    # activation tables: 1024 intervals; outside the range the op clamps
    table(img, "tab.gelu", gelu, -8.0, 8.0, 1024, "GELU over [-8, 8): (value, slope); below 0, above x")
    table(img, "tab.sigmoid", lambda x: 1 / (1 + np.exp(-x)), -16.0, 16.0, 1024, "sigmoid over [-16, 16)")
    table(img, "tab.tanh", np.tanh, -8.0, 8.0, 1024, "tanh over [-8, 8)")
    # layer norm: 1/sqrt(m) / 2 for m in [1/2, 2) in steps of 1/256, Q0.23
    # (values, then slopes): see fixed.h's layernorm
    m = 0.5 + np.arange(385) / 256
    r = np.round(0.5 / np.sqrt(m) * (1 << 23)).astype(np.int64)
    r = np.minimum(r, (1 << 23) - 1)
    img.add("tab.rsqrt", pairs(r), None,
            "rsqrt(m)/2 for m in [1/2, 2), 384 intervals of 1/256, Q0.23")

    # length regulator (68030 side): softmax weights exp(-q / (8 sigma^2)) for
    # q = d^2 - dmin^2 with d twice the frame-to-centre distance, Q0.23
    sigma = math.log1p(math.exp(float(W["sigma_raw"])))
    e = []
    qv = 0
    while True:
        v = round(math.exp(-qv / (8 * sigma * sigma)) * (1 << 23))
        if v == 0:
            break
        e.append(min(v, (1 << 23) - 1))
        qv += 1
    img.add("tab.upw", e, None, f"length regulator weights, sigma {sigma:.6f}, by d^2 - dmin^2")
    img.add("tab.logdur", [0] + [int(round(math.log(n) * ONE)) for n in range(1, 256)], None,
            "log(duration) Q7.16 for duration 0..255")
    # duration n (>= 2) needs logd >= ln(n + 0.5); duration is at least 1, at most 255
    img.add("tab.durth", [0, 0] + [int(math.ceil(math.log(n + 0.5) * ONE)) for n in range(2, 256)], None,
            "duration thresholds: logd Q7.16 at or above entry n gives at least n")

    synth_tables(img, W, cfg)

    args.out.mkdir(parents=True, exist_ok=True)
    args.header.parent.mkdir(parents=True, exist_ok=True)
    meta = dict(f0_mean=cfg["f0_mean"], f0_std=cfg["f0_std"], sigma=sigma)
    img.write(args.out / "AURORA.BIN", args.header)
    (args.out / "aurora-meta.json").write_text(json.dumps(meta, indent=1) + "\n")
    print(f"{len(img.words)} words, {len(img.blocks)} blocks -> {args.out / 'AURORA.BIN'}")


if __name__ == "__main__":
    main()
