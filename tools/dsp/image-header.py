#!/usr/bin/env python3
"""Emit the DSP kernel's boot and program images as a C header for the 68030
program: Dsp_ExecBoot takes the stage-two loader, which then receives the
kernel's P sections through the host port."""
import argparse
import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--bootstrap", type=Path, required=True)
    ap.add_argument("--program", type=Path, required=True)
    ap.add_argument("--output", type=Path, required=True)
    args = ap.parse_args()
    spec = importlib.util.spec_from_file_location("stage2", HERE / "generate_dsp_stage2.py")
    stage2 = importlib.util.module_from_spec(spec)
    sys.modules["stage2"] = stage2
    spec.loader.exec_module(stage2)
    boot = stage2.make_boot_image(args.bootstrap)
    stream, sections, words = stage2.make_program_stream(args.program)
    for s in stage2.parse_lod(args.program)[0]:
        if s.space == "P" and s.address < 0x0200 and s.limit > 0x0200:
            raise SystemExit("error: hot code exceeds internal P RAM ($0000-$01ff)")
        if s.space == "P" and 0x0200 <= s.address < 0x7000:
            raise SystemExit(f"error: P:${s.address:04x} lies in data memory; code belongs at $7000-$7fff")
        if s.space == "P" and s.limit > 0x8000:
            raise SystemExit("error: code runs past P:$7fff")

    def rows(values, per, fmt):
        return "\n".join("\t" + ", ".join(fmt % v for v in values[i:i + per]) + "," for i in range(0, len(values), per))

    boot_bytes = []
    for w in boot:
        boot_bytes += [(w >> 16) & 0xff, (w >> 8) & 0xff, w & 0xff]
    text = (
        "/* Generated by tools/dsp/image-header.py from dsp/aurora.asm. Do not edit. */\n"
        "#pragma once\n\n"
        "#define AURORA_DSP_BOOT_WORDS %d\n"
        "static const unsigned char kAuroraDspBoot[%d] = {\n%s\n};\n\n"
        "/* stage two: magic, section count, then per section address, length, words (%d program words) */\n"
        "#define AURORA_DSP_STREAM_WORDS %d\n"
        "#define AURORA_DSP_STREAM_REPLY_OK 0x%06x\n"
        "static const unsigned long kAuroraDspStream[%d] = {\n%s\n};\n"
    ) % (len(boot), len(boot_bytes), rows(boot_bytes, 12, "0x%02x"), words, len(stream), stage2.STAGE2_REPLY_OK,
         len(stream), rows(stream, 8, "0x%06x"))
    args.output.write_text(text)
    print(f"{args.output}: {len(boot)} boot words, {words} program words in {sections} sections")


if __name__ == "__main__":
    main()
